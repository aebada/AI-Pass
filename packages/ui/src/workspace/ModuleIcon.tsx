const FALLBACK: ModuleIconName = 'layout-grid';

export function isModuleIconName(name: string): name is ModuleIconName {
  return name in ICONS;
}

export interface ModuleIconProps {
  name: string;
  active?: boolean;
  className?: string;
  size?: number;
}

export function ModuleIcon({ name, active = false, className, size = 20 }: ModuleIconProps) {
  const iconName = isModuleIconName(name) ? name : FALLBACK;
  const classes = ['ws-nav-icon', active ? 'ws-nav-icon--active' : '', className].filter(Boolean).join(' ');
  const icon = ICONS[iconName];

  return (
    <span className={classes} style={{ width: size, height: size }}>
      {isValidElement(icon)
        ? cloneElement(icon as React.ReactElement<SVGProps<SVGSVGElement>>, { width: size, height: size })
        : icon}
    </span>
  );
}
